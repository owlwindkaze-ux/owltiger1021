FILES = ['grammar-n5.json', 'grammar-n4.json', 'grammar-n3.json']
apply = '--apply' in sys.argv
items, unmapped, after = [], [], collections.Counter()

for f in FILES:
    d = json.load(io.open(f, encoding='utf-8'))
    for g in d['grammar']:
        old = g['category']
        new = MAP.get(old)
        if new is None:
            unmapped.append((g['id'], old))
            continue
        after[new] += 1
        items.append((new, g['pattern']))
        if apply:
            g['category'] = new
    if apply:
        io.open(f, 'w', encoding='utf-8').write(json.dumps(d, ensure_ascii=False, indent=1))

