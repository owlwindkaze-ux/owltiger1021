/* すでにルビを付けた場所を壊さないよう、いったん印に置きかえてから戻す。
   印には私用領域の文字を使う（本文には出てこないので、数字と混ざらない）。 */
const MARK = '\uE000';
function withRuby(text) {
  let s = String(text == null ? '' : text);
  const box = [];
  RUBY.forEach(([w, r]) => {
    if (!s.includes(w)) return;
    s = s.split(w).join(MARK + box.length + MARK);
    box.push('<ruby>' + w + '<rt>' + r + '</rt></ruby>');
  });
  /* 数と助数詞は、語として登録できない（数がいくつでも来る）ので、あとから付ける。
     「分」は「ふん」と「ぶん」で読みが変わるため、数のうしろだけ「ふん」にする。 */
  const NUM = [['階','かい'], ['回','かい'], ['部','ぶ'], ['分','ふん'], ['問','もん'], ['週','しゅう'], ['点','てん'], ['字','じ'], ['語','ご'], ['期','き'], ['本','ほん'], ['名','めい']];
  NUM.forEach(([w, r]) => {
    s = s.replace(new RegExp('([0-9０-９]+)' + w, 'g'),
      (m, n) => n + '<ruby>' + w + '<rt>' + r + '</rt></ruby>');
  });
  /* 辞書で当てた所を戻すのは いちばん最後。先に戻すと「7時30分」の中の「30分」に
     もう一度ルビが付いて、ルビの中にルビが入ってしまう（紙で崩れる）。 */
  s = s.replace(new RegExp(MARK + '(\\d+)' + MARK, 'g'), (_, i) => box[+i]);
  return s;
}
module.exports = { withRuby, RUBY };
