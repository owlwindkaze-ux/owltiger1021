def psg(pid, title, text, qs, intro=None, table=None):
    p = {"id": pid, "level": "N3", "type": "moshi", "title": title, "text": text, "questions": qs}
    if intro: p["intro"] = intro
    if table: p["table"] = table
    return {"passage": p, "qi": list(range(len(qs)))}

def rq(q, ch, a, ex): return {"qtype": "内容", "q": q, "choices": ch, "answer": a, "explain": ex}

