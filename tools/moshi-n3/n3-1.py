# --- 正解の番号を 散らす ---------------------------------------------
# 00のまとめの「正解の位置を必ず散らす」。文も 正解も 変えず、
# 選択肢を 入れかえて 正解の 位置だけ 動かす。
# 数字や 時刻のように **順番に 意味が ある** 並びは 動かさない。
import re as _re
_NUM = _re.compile(r'^[〇一二三四五六七八九十百千万\d]+[時分円日人番]?')
def _ordered(ch):
    ks = [_NUM.match(_re.sub(r'\s', '', c)) for c in ch]
    return all(ks)
def _refs():
    out = []
    for k in ORDER:
        s = SECTIONS[k]
        for x in (s.get("items") or []):
            ck = "choices" if "choices" in x else "opts"
            ak = "answer" if "answer" in x else "ans"
            out.append((k, x, ck, ak))
        for r in (s.get("read") or []):
            for qi in r["qi"]:
                out.append((k, r["passage"]["questions"][qi], "choices", "answer"))
    return out
def _balance():
    cnt = {0:0, 1:0, 2:0, 3:0}
    moved = skipped = 0
    for k, x, ck, ak in _refs():
        ch, a = x[ck], x[ak]
        if _ordered(ch):
            cnt[a] += 1; skipped += 1; continue
        want = min(range(len(ch)), key=lambda i: (cnt[i], i))
        if want != a:
            ch[a], ch[want] = ch[want], ch[a]
            x[ak] = want; moved += 1
        cnt[x[ak]] += 1
    return cnt, moved, skipped
_cnt, _moved, _skip = _balance()
