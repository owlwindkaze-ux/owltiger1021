# --- 正解の番号を 散らす（選択肢の 並べかえだけ。文も 正解も 変えない） ---
_NUM = re.compile(r'^[〇一二三四五六七八九十百千万\d]+[時分円日人番]?')
def _ordered(ch): return all(_NUM.match(re.sub(r'\s','',c)) for c in ch)
def _refs():
    out = []
    for k in ORDER:
        s = SECTIONS[k]
        for x in (s.get("items") or []):
            out.append((x, "choices" if "choices" in x else "opts",
                           "answer" if "answer" in x else "ans"))
        for r in (s.get("read") or []):
            for qi in r["qi"]:
                out.append((r["passage"]["questions"][qi], "choices", "answer"))
    return out
def _balance():
    cnt = {0:0,1:0,2:0,3:0}; moved = skipped = 0
    for x, ck, ak in _refs():
        ch, a = x[ck], x[ak]
        if _ordered(ch): cnt[a] += 1; skipped += 1; continue
        want = min(range(len(ch)), key=lambda i: (cnt[i], i))
        if want != a:
            ch[a], ch[want] = ch[want], ch[a]; x[ak] = want; moved += 1
        cnt[x[ak]] += 1
    return cnt, moved, skipped
_cnt, _moved, _skip = _balance()
print('  正解の位置を ならした：%d問 動かし、%d問は そのまま' % (_moved, _skip))
print('  ならしたあと:', dict(sorted(_cnt.items())))

def nq(k):
    s = SECTIONS[k]
    if s.get("read"): return sum(len(r["qi"]) for r in s["read"])
    return len(s.get("items") or [])
