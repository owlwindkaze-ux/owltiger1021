#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""語彙の「学習区分」の下書きを作る（SPEC 2.6-z29・方針はドライブ08）。

  覚える      自分で言う・自分で書く
  意味が分かる  読んで分かればよい。自分では書かない
  参考        出てきたら引く

**分ける軸は 難しさではなく「その語で何をするか」。**
方針（ドライブ08「N4実習生向け介護日本語教材の作成・改善方針」）が挙げている
例を そのまま 判定の基準点にする。

  覚える       交換・更衣・発赤・体位交換
  意味が分かる   拘縮・喘鳴・意識混濁
  参考         良肢位・びらん・薬剤名（ソフラチュール）

**迷ったら上に寄せる。**
「参考」にした語は実習生が飛ばすので、まちがえると取り返しがつかない。
逆に「覚える」にしすぎても負担が少し増えるだけ。
そこで **`REF`（参考）と `READ`（意味が分かる）だけを名指しし、
書き落としたものは全部「覚える」に残る**ようにしてある。

    python3 tools/vocab-study.py            # 下書きを見る
    python3 tools/vocab-study.py --md FILE  # 確認用の紙（Markdown）を書き出す

**この道具は vocab-data.json を書き換えません。**下書きを見せるだけ。
確認が済んでから、別の手順でデータに入れる。
"""
import collections
import io
import json
import os
import sys

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__))) + '/'
SUB = '記録の言葉'

# ---- 参考：出てきたら引く ----------------------------------------------
# A 商品名・規格・単位・記号。意味を知ってもケアは変わらない
REF_A = {
    'ペロール注500mL', 'サーフロ針', '24G', 'Fr', '生理食塩液', 'アイスノン',
    'OS-1', 'ギャザパン', '眠りSCAN', 'アンクルクロス', 'バルーンチューブ',
    'コアグラ',
}
# B 医師・看護師が使う専門語で、介護職員は書かない
#    方針が「参考」の例に挙げた 良肢位・びらん と同じ重さのもの
REF_B = {
    '良肢位', 'びらん', '粉瘤', '真菌', 'ヘルペス', '骨粗鬆症', '色素沈着',
    '膿性', '硬結', '爪甲脱落', 'いぼ様', '皮下脂肪', '内臓脂肪', 'ミルキング',
}
# C 記録に書いてはいけない言い方（データにあるのは実際の記録から拾ったため）
REF_C = {
    '脳みそ',
}
REF = REF_A | REF_B | REF_C

# ---- 意味が分かる：読んで分かればよい ------------------------------------
# A 看護師・医師が書く観察の語。方針の「喘鳴・拘縮・意識混濁」と同じ重さ
READ_A = {
    '振戦', '悪寒戦慄', '喘鳴', '流涎', '眼脂', '食思', '隆起', '腸蠕動音',
    '低体温', '慢性心不全', 'てんかん発作', 'てんかん様状態', '多動',
    '肺雑音', 'エアー入り', '副雑音', '粘稠度', '見当識障害', '歯の動揺',
    '乾性咳嗽', '湿性咳嗽', '咳嗽', '嗄声', '鼻閉感', '嘔気', '吐瀉物',
    '胃液', '残渣物', '食物残渣', '腹部膨満', '腹部緊満', '腸音', '混濁',
    '閉塞', '貯留', 'ガス貯留', '腹満', '表皮剥離', '皮膚剥離', '掻痒',
    '掻痒感', '排膿', '後屈', '前屈', '眼瞼', '抜去', '酸素投与', '端座位',
    '四肢', '口腔', '口腔内', '腋窩', '頭皮', '足底',
}
# B 施設の中だけで通じる言い方・記録の書式。読めればよく、書くのは普通の形で
READ_B = {
    '帰荘', 'ルート確保', '来荘', 'Pトイレ', '自操', 'コンサル', 'サマリー', '打診する',
    '打診中', 'A・Bともに', 'A及びB', 'AからBへ', 'U字', '著変', '特変',
    '軽微', '著明', '中等量', '超多量', '微量', '乳白色', '黄白色',
}
READ = READ_A | READ_B

LABEL = ['覚える', '意味が分かる', '参考']


def classify(word):
    if word in REF:
        return '参考'
    if word in READ:
        return '意味が分かる'
    return '覚える'


def main():
    words = json.load(io.open(R + 'vocab-data.json', encoding='utf-8'))['words']
    target = [x for x in words if x.get('sub') == SUB]

    # 名指ししたのに その区分に実在しない語があれば、書きまちがい
    have = {x['word'] for x in target}
    miss = sorted((REF | READ) - have)
    if miss:
        print('× 「記録の言葉」に無い語を名指ししています: ' + '　'.join(miss))
        return 1

    out = collections.OrderedDict((k, []) for k in LABEL)
    for x in target:
        out[classify(x['word'])].append(x)

    print('■ 「%s」%d語の下書き' % (SUB, len(target)))
    for k in LABEL:
        print('   %-7s %4d語（%d%%）' % (k, len(out[k]), round(100 * len(out[k]) / len(target))))
    print('\n※ 名指ししたのは 参考%d語・意味が分かる%d語だけ。残りは全部「覚える」に残る。'
          % (len(REF), len(READ)))

    if '--md' in sys.argv:
        p = sys.argv[sys.argv.index('--md') + 1]
        io.open(p, 'w', encoding='utf-8').write(markdown(out, len(target)))
        print('\n確認用の紙を書きました: ' + p)
    return 0


def markdown(out, total):
    def rows(items):
        s = ''
        for x in items:
            s += '| %s | %s | %s |\n' % (
                x['word'], x['reading'],
                (x.get('meaning_ja') or x.get('meaning') or '').replace('|', '／'))
        return s

    s = '# 記録の言葉 %d語　学習区分の下書き\n\n' % total
    s += ('ドライブ08の方針「覚える／意味が分かる／参考」を、'
          '語彙データの「記録の言葉」に当てた**下書き**です。\n'
          '**まだデータには入れていません。**\n\n')
    s += '| 区分 | 語数 | 画面での出方 |\n|---|---|---|\n'
    s += ('| 覚える | %d語 | 週割り・カード・練習問題・「覚えた」の分母に入る |\n'
          % len(out['覚える']))
    s += ('| 意味が分かる | %d語 | 一覧と検索には出る。練習は意味を選ぶ問題だけ。**分母に入れない** |\n'
          % len(out['意味が分かる']))
    s += ('| 参考 | %d語 | **検索だけ。**週割りにも練習にも出さない |\n\n'
          % len(out['参考']))
    s += ('**見ていただきたいのは「参考」の%d語です。**\n'
          'ここに入れた語は実習生が飛ばすので、1つでも混ざっていたら教えてください。\n'
          '「意味が分かる」は飛ばさない（読む練習には出る）ので、急ぎません。\n\n'
          % len(out['参考']))
    s += '---\n\n## 参考 ── %d語（**ここを見てください**）\n\n' % len(out['参考'])
    s += ('出てきたら引けばよい語です。商品名・規格・単位と、'
          '介護職員が書かない専門語、それに記録に書いてはいけない言い方。\n\n')
    s += '| 語 | 読み | 意味 |\n|---|---|---|\n' + rows(out['参考']) + '\n'
    s += '---\n\n## 意味が分かる ── %d語\n\n' % len(out['意味が分かる'])
    s += ('読んで分かればよい語です。看護師・医師が書く観察の語と、'
          '施設の中だけで通じる言い方。\n\n')
    s += '| 語 | 読み | 意味 |\n|---|---|---|\n' + rows(out['意味が分かる']) + '\n'
    s += '---\n\n## 覚える ── %d語\n\n' % len(out['覚える'])
    s += ('自分で言う・自分で書く語です。**名指ししなかった語は全部ここに残ります。**\n'
          '「迷ったら上に寄せる」ためで、取りこぼしても負担が少し増えるだけで済みます。\n\n')
    s += '| 語 | 読み | 意味 |\n|---|---|---|\n' + rows(out['覚える']) + '\n'
    return s


if __name__ == '__main__':
    sys.exit(main())
