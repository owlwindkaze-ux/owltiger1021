def main():
    t = build()
    if '--md' in sys.argv:
        p = sys.argv[sys.argv.index('--md') + 1]
        io.open(p, 'w', encoding='utf-8').write(t)
        print('書きました: %s（%d文字）' % (p, len(t)))
    else:
        print(t)
    return 0


