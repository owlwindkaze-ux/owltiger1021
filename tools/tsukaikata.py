FIRST = ['新人コース（N4 → 7月のN3）', '漢字・言葉（語彙）', 'まちがえたところ']


def menu():
    """入口メニューから、まとまりの見出しと ボタンの名前を読む。

    作りは <section class="card…"> の中の
      <div class="ttl">ローマ字<small>日本語の見出し</small></div>
      <span class="n">ボタンの名前</span>
    """
    s = io.open(R + 'index.html', encoding='utf-8').read()
    out = []
    for m in re.finditer(r'<section class="card[^"]*">(.*?)</section>', s, re.S):
        blk = m.group(1)
        t = re.search(r'<div class="ttl">.*?<small>(.*?)</small>', blk, re.S)
        if not t:
            continue
        jp = re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', t.group(1))).strip()
        names = [re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', a.group(1))).strip()
                 for a in re.finditer(r'<span class="n">(.*?)</span>', blk, re.S)]
        if jp:
            out.append((jp, names))
    # **1つも読めなかったら止める。**前に 0個のまま素通りして、
    # 中身の無い説明書ができた（2026-10-14）。
    if len(out) < 5:
        raise SystemExit('× メニューが %d個しか読めませんでした。'
                         'index.html の作りが変わった可能性があります。' % len(out))
    return out


def nums():
    def J(p):
        return json.load(io.open(R + p, encoding='utf-8'))
    v = J('vocab-data.json')['words']
    return {
        'kanji': len(J('kanji-data.json')['kanji']),
        'vocab': len(v),
        'gram': J('bunpo/grammar.json')['total'],
        'read': J('dokkai/reading.json').get('totals', {}).get('passages', 0),
        'tegaki': len(J('tegaki-data.json').get('chars', [])),
    }


