def drive():
    """ドライブにある答え入りの一覧。**OUT と食い違えば止まる。**"""
    import importlib.util
    sp = importlib.util.spec_from_file_location('ao', R + 'tools/check-answers-out.py')
    mo = importlib.util.module_from_spec(sp)
    sp.loader.exec_module(mo)
    out = set(mo.OUT)
    miss = sorted(out - set(DRIVE))
    extra = sorted(set(DRIVE) - out)
    if miss:
        raise SystemExit('× ドライブにあるのに 説明が無いものがあります: '
                         + '／'.join(miss)
                         + '\n  tools/matome.py の DRIVE に足してください。')
    if extra:
        raise SystemExit('× DRIVE にあるのに check-answers-out.py の OUT に無い: '
                         + '／'.join(extra)
                         + '\n  どちらかが古くなっています。')
    return [(DRIVE[k][0], DRIVE[k][1]) for k in mo.OUT]


def J(p):
    return json.load(io.open(R + p, encoding='utf-8'))


def kami():
    """紙の教材の入口を読む。**説明の無いものがあれば止まる。**"""
    s = io.open(R + 'kaigo/index.html', encoding='utf-8').read()
    out = []
    for m in re.finditer(r'<span class="n">(.*?)</span>\s*<span class="r">(.*?)</span>',
                         s, re.S):
        n = re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', m.group(1))).strip()
        # 「🔒 ドライブ」「巻末に解答」などの札を落として 名前だけにする
        n = re.sub(r'(巻末に解答|巻末にスクリプト|実技|職員用|最初に読む|参考|別のログイン'
                   r'|🔒\s*ドライブ)', '', n).strip()
        r = re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', m.group(2))).strip()
        out.append((n, r.split('／')[0].strip()))
    if len(out) < 10:
        raise SystemExit('× 紙の教材が %d件しか読めませんでした。'
                         'kaigo/index.html の作りが変わった可能性があります。' % len(out))
    miss = [n for n, _ in out if n not in KAMI]
    if miss:
        raise SystemExit('× 説明の無い教材があります: ' + '／'.join(miss)
                         + '\n  tools/matome.py の KAMI に足してください。')
    return out


def gamen():
    """画面のほうの数を そのときのデータから数える"""
    ix = io.open(R + 'index.html', encoding='utf-8').read()
    ch = io.open(R + 'choukai/index.html', encoding='utf-8').read()
    i = ch.index('const DATA = [')
    parts = json.loads(ch[i + len('const DATA = '):ch.index('\n];', i) + 2])
    kw = J('kanji-weeks.json')['courses']
    gw = J('bunpo/weeks.json')['courses']
    d = {
     'kanji': J('kanji.json')['total'],
     'vocab': J('vocab.json')['total'],
     'gram': J('bunpo/grammar.json')['total'],
     'read': J('dokkai/reading.json')['totals'],
     'choukai': int(re.search(r'CTOTAL = (\d+)', ix).group(1)),
     'parts': len(parts),
     'tegaki': len(J('tegaki-data.json').get('chars', [])),
     'pages': sorted(os.path.relpath(p, R) for p in
                     glob.glob(R + '*.html') + glob.glob(R + '*/index.html')),
     'moshi': len(glob.glob(R + 'moshi/moshi-*.json')) + len(glob.glob(R + 'moshi/n3-*.json')),
     'unit': len(glob.glob(R + 'moshi/n2u-*.json')),
     'ver': J('version.json')['version'],
    }
    for c, key in (('shinjin', '新人'), ('n2', 'N2')):
        d[c] = {'start': kw[c]['start'], 'total': kw[c]['total'],
                'kanji': sum(len(x) for x in kw[c]['kanji'].values()),
                'vocab': sum(len(x) for x in kw[c]['vocab'].values()),
                'gram': sum(len(x) for x in gw[c]['weeks'].values())}
    return d


