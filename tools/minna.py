def grammar():
    """システムの文型を 言い方で引けるようにする"""
    g = json.load(io.open(R + 'bunpo/grammar.json', encoding='utf-8'))
    by = {}
    for f in g['files']:
        d = json.load(io.open(R + 'bunpo/' + f['file'], encoding='utf-8'))
        for x in d['grammar']:
            by[x['pattern']] = (f['level'], x.get('category', ''))
    return by, g['total'], g['level_totals']


def have():
    """「この本で育たないもの」を 何で補うか。**数は手で書かない。**"""
    k = json.load(io.open(R + 'kanji.json', encoding='utf-8'))
    r = json.load(io.open(R + 'dokkai/reading.json', encoding='utf-8'))['totals']
    import re as _re
    ix = io.open(R + 'index.html', encoding='utf-8').read()
    m = _re.search(r'CTOTAL = (\d+)', ix)
    return {'kanji': k['total'], 'read': r['passages'], 'readq': r['questions'],
            'choukai': int(m.group(1)) if m else 0}


def check(by):
    """紙が指している文型が、ぜんぶ データに あるか。

    **無ければ止める。**「次はこれをやりなさい」と紙に書いたのに
    画面に その項目が無い、が いちばん困る。
    """
    miss = []
    for k in KANSEKI:
        for p in k['pats']:
            if p not in by:
                miss.append('第%d課「%s」→ %s' % (k['ka'], k['form'], p))
    for p in OMAKE['pats']:
        if p not in by:
            miss.append('第%d課「%s」→ %s' % (OMAKE['ka'], OMAKE['form'], p))
    if miss:
        raise SystemExit('× 紙が さしている文型が データに ありません:\n  '
                         + '\n  '.join(miss)
                         + '\n  文型を 消した／名前を 変えたのなら、'
                           'tools/minna.py の pats も 直してください。')


