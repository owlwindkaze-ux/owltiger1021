BLANK = '＿＿＿＿＿＿＿＿'
MARU = '①②③④⑤'


def part2(tag, pair, ans=None):
    """（2）の1行。（　）のことばを かえて、空欄に入れる形。

    ans を渡すと れい（答え入り）、渡さなければ 問い（空欄）。
    **文は こちらで 用意する。**「文を作ってください」では
    何を書けばよいか 分からなかったため（2026-10-16）。
    """
    word, sent, a = pair
    return '| **%s** | （%s） | %s |' % (tag, word, sent % ('**%s**' % a if ans else BLANK))


