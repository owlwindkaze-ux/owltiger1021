def main():
    by, total, lvt = grammar()
    check(by)
    if '--staff' in sys.argv:
        p = sys.argv[sys.argv.index('--staff') + 1]
        t = md_s(by, total, lvt, have())
    elif '--md' in sys.argv:
        p = sys.argv[sys.argv.index('--md') + 1]
        t = md_q(by)
    else:
        sys.stdout.write(md_q(by))
        return 0
    io.open(p, 'w', encoding='utf-8').write(t)
    print('書きました: %s（%d文字）' % (p, len(t)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
